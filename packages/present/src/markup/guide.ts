// (docs/TEXT-MARKUP.md), the tutor's text tools and the course format's paragraph on text
// (packages/ai/src/prompts/markup.generated.ts). One source, so what a model is told is what the page does.
import { audience_of } from '../../../engine/src/kernel/registry';
import { markup_entries, type MarkupEntry } from './registry';

const INTRO = `One page for whoever writes text for a page (a person, the course generator, the margin tutor). Every piece below
works in any prose: a lesson's \`p\` block, a caption, a tutor's answer. Each is checked and has a plain fallback, so a
mistake shows as plain text, never as a broken page. Design: \`docs/design/ENGINE-ZONES.md\` (the text zone),
\`docs/design/ENGINE-ARCH.md\` (how a tool is added), \`docs/design/specimen\` (the experiments they come from).`;

const LESSON_DATA = `## In lesson data

The same pieces as blocks (\`packages/core/src/content.ts\`): \`{ "type": "why", "claim", "because": [{ "text", "kind"?,
"because"? }] }\`; \`{ "type": "steps", "lines": [{ "tex", "why"? }], "nouns"? }\`; \`{ "type": "math", "tex", "parts": [{
"tex", "says" }] }\`; \`{ "type": "details", "summary", "blocks" }\`; \`{ "type": "visual", …, "bind": { "<figure param>":
"<number's name>" } }\` (the figure follows a number of the page's text, and moves it back). Inline pieces (nouns,
definitions, numbers) go in any text string.`;

const RULES = `## Rules of use

- One of each where it helps; a page is not a showcase. A definition only for a term this reader may not know; a
  chain of why only for a claim a reader would doubt; numbers to drag only where "what if it were bigger?" is the
  point.
- Nouns: only the nouns the page's figures draw (their roles), so the colour means the same thing in both.
- Never instructions in the text ("tap the ring", "drag the number"): the page shows what can be done.

## Adding a tool

A new tool is one file in \`packages/present/src/markup/\` with its \`define_markup\` entry: how it is written, what the
learner sees, the words the tutor and the course generator are told, a \`check\` for a malformed use, and its renderer
(\`html\`; \`pattern\` for an inline one). It starts as \`maturity: 'experiment'\` (the gallery only), and this guide, the
tutor's prompt and the course format pick it up when it is promoted (\`npm run catalog\`).`;

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
/** How a tool is written, for the table: a fence by its name; an inline tool as written, another form, a word on it. */
const write = (e: MarkupEntry) =>
  e.form === 'fence' ? `a \`\`\`\` \`\`\`${e.fence} \`\`\`\` fence (below)` : `\`${cell(e.syntax)}\`${e.example ? ` or \`${cell(e.example)}\`` : ''}${e.note ? ` (${e.note})` : ''}`;
const who = (e: MarkupEntry) => (audience_of(e).includes('tutor') ? 'everyone, the tutor too' : 'course authors');

/** docs/TEXT-MARKUP.md: every text tool authors may use (stable and preview). */
export function markup_guide(): string {
  const all = markup_entries({ audience: 'author' });
  const tabled = all.filter((e) => !e.also), also = all.filter((e) => e.also);
  const out = [
    '# Text markup: what any text in Mathium can hold', '',
    '<!-- Generated by `npm run catalog` from the text tools\' entries (packages/present/src/markup/). Edit those, not this. -->', '',
    INTRO, '',
    '| You want | Write | The learner sees | For |', '|---|---|---|---|',
    ...tabled.map((e) => `| ${cell(e.says.en)} | ${write(e)} | ${cell(e.shows)} | ${who(e)} |`),
    '', `Also: ${also.map((e) => e.syntax).join('; ')}.`,
  ];
  for (const e of tabled.filter((x) => x.form === 'fence')) {
    out.push('', e.example ?? '', '', (e.rules ?? []).map((r) => r[0].toUpperCase() + r.slice(1)).join('. ') + '.');
  }
  const inline_rules = tabled.filter((x) => x.form === 'inline' && x.rules?.length);
  if (inline_rules.length) out.push('', ...inline_rules.map((e) => `- **${e.name}**: ${e.rules!.join('; ')}.`));
  out.push('', LESSON_DATA, '', RULES, '');
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

/** The tutor's part of its rules: the tools it may write, in its own words (stable tools only). */
export function markup_tutor(): string {
  const all = markup_entries({ audience: 'tutor' }).filter((e) => e.tutor !== null).sort((a, b) => (a.tutor_order ?? a.order) - (b.tutor_order ?? b.order));
  const line = (e: MarkupEntry) => e.tutor ?? `${e.says.en}: ${e.syntax}`;
  // (a derivation has its own paragraph: it is the tool the tutor reaches for most, with the most rules)
  const lead = all.filter((e) => e.name === 'steps'), rest = all.filter((e) => e.name !== 'steps');
  return [
    ...lead.map(line),
    ...(rest.length ? ['', 'Text tools (use one only when it is what the student needs; they do not count toward the 80 words):', ...rest.map((e) => `- ${line(e)}`)] : []),
  ].join('\n');
}

/** The course format's paragraph on what a text string may hold. */
export function markup_lesson(): string {
  const parts = markup_entries({ audience: 'author' }).filter((e) => e.lesson).map((e) => e.lesson!);
  return `Text in strings: ${parts.join(',\n')}.`;
}
