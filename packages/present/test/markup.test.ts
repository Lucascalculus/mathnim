// The text tools as entries (src/markup): every built-in tool is registered; the guides are written from them (the
// authors' guide, the tutor's tools, the course format's paragraph) and say only what each audience may use; the check
// catches each kind of malformed use and passes the guide's own examples; a tool added by a file renders through
// math_html, and falls back to prose when its renderer gives up.
import { describe, expect, it } from 'vitest';
import { define_markup, markup_entries, markup_guide, markup_issues, markup_lesson, markup_tutor, number_names } from '../src/markup';
import { math_html } from '../src/math';

const t = (en: string, zh: string) => ({ en, zh });

describe('the text tools', () => {
  it('are all registered, in the guides\' order', () => {
    expect(markup_entries().filter((e) => e.source.endsWith('builtin.ts')).map((e) => e.name)).toEqual(['prose', 'noun', 'def', 'number', 'computed', 'why', 'steps', 'parts', 'details', 'footnote']);
  });
  it('the authors\' guide shows every tool authors may use, with its example', () => {
    const g = markup_guide();
    for (const s of ['[cost](noun:cost)', '[convex](def:', '{{n = 3, 1..12}}', '{{= 2.5*n, 2}}', '```why', '```steps', '```parts', '```details', '[^key]']) expect(g, s).toContain(s);
    expect(g).toContain('Generated by `npm run catalog`');
    expect(g).toContain('## Adding a tool');
  });
  it('the tutor is told only what it may write, in the words it has always been told', () => {
    const s = markup_tutor();
    expect(s.startsWith('Steps: when the answer is a short derivation')).toBe(true);
    expect(s).toContain('Text tools (use one only when it is what the student needs; they do not count toward the 80 words):');
    expect(s).toContain('- A term the student may not know: [term](def: what it means in a short phrase).');
    expect(s).toContain('```why\nThe ball stops at the wall.');
    expect(s).toContain('{{= 2.5*n, 2}} follows it (2 decimals)');
    expect(s).toContain('without \\\\ or &');
    // (nouns, folded details and sources need a page the tutor cannot see)
    expect(s).not.toContain('noun:');
    expect(s).not.toContain('```details');
  });
  it('the course format\'s paragraph says what a text string may hold', () => {
    const s = markup_lesson();
    expect(s.startsWith('Text in strings: inline TeX between $...$')).toBe(true);
    expect(s).toContain('[term](def: what it means)');
    expect(s).toContain('{{n = 3, 1..12}} (value, range)');
  });
});

describe('the check of a text\'s markup', () => {
  it('passes the guide\'s own examples', () => {
    for (const e of markup_entries()) if (e.example && e.form === 'fence') expect(markup_issues(e.example), e.name).toEqual([]);
    expect(markup_issues('You buy {{n = 3, 1..12}} cups at $2.50: that is {{= 2.5*n, 2}} dollars, a [cup](def: a measure (about 240 ml)).')).toEqual([]);
  });
  it('says what is wrong, in words a model can act on', () => {
    expect(markup_issues('A [term](def: never closed').join()).toContain('definition is not closed');
    expect(markup_issues('{{n = three}}').join()).toContain('not a number the page can read');
    expect(markup_issues('that is {{= 2*k}}').join()).toContain('reads "k"');
    expect(markup_issues('that is {{= 2*k}}', { names: ['k'] })).toEqual([]);
    expect(markup_issues('```steps\nx = 1\n```').join()).toContain('at least 2 lines');
    expect(markup_issues('```steps\na = b \\\\ c = d\ne = f\n```').join()).toContain('without \\\\ or &');
    expect(markup_issues('```why\n- a reason without a claim\n```').join()).toContain('first line is the claim');
    expect(markup_issues('```why\nClaim.\n- a\n  - b\n    - c\n      - d\n```').join()).toContain('at most three deep');
    expect(markup_issues('```parts\nF = ma\nG: gravity\n```').join()).toContain('"G" is not written that way');
    expect(markup_issues('```details\nbody\n```').join()).toContain('title goes on the fence line');
    expect(markup_issues('```why\nClaim.\n- reason').join()).toContain('not closed');
    expect(markup_issues('a {{ left open').join()).toContain('without its "}}"');
  });
  it('knows which numbers a text defines', () => {
    expect(number_names('{{n = 3, 1..12}} and {{rate = 0.5, 0..2, 0.1}} and {{= n*rate}}')).toEqual(['n', 'rate']);
  });
});

describe('a tool added by a file', () => {
  it('a fence renders through math_html, and a renderer that gives up leaves prose', () => {
    define_markup({ name: 'test_box', form: 'fence', fence: 'testbox', order: 999, zones: ['text'], maturity: 'experiment', since: '0.3.0', source: 'test/markup.test.ts', says: t('a box', '一个框'), syntax: '```testbox … ```', shows: 'a box', html: (body, head, ctx) => (body.includes('give up') ? null : `<div class="tb" data-head="${ctx.esc(head)}">${ctx.prose(body.trim())}</div>`) });
    expect(math_html('Before.\n```testbox Title\nSome **bold** $x$\n```\nAfter.')).toContain('<div class="tb" data-head="Title">Some <b>bold</b>');
    expect(math_html('```testbox\ngive up\n```')).toContain('give up');
    // (an experiment: the gallery sees it, the guides do not)
    expect(markup_guide()).not.toContain('testbox');
    expect(markup_tutor()).not.toContain('testbox');
  });
  it('an inline tool renders on the prose it is in', () => {
    define_markup({ name: 'test_kbd', form: 'inline', order: 998, zones: ['text'], maturity: 'experiment', since: '0.3.0', source: 'test/markup.test.ts', says: t('a key', '一个键'), syntax: '((Enter))', shows: 'a key cap', pattern: /\(\((\w+)\)\)/g, html: (_m, key) => `<kbd>${key}</kbd>` });
    expect(math_html('press ((Enter)) now')).toContain('press <kbd>Enter</kbd> now');
  });
});
