describe('the paper\'s table', () => {
  it('equals common.ztable at every entry from -3.49 to 3.49', () => {
    const bad: string[] = [];
    for (let k = -349; k <= 349; k++) {
      const want = Number(TABLE.slice((k + 349) * 4, (k + 349) * 4 + 4)) / 10000;
      if (ztable(k / 100) !== want) bad.push(`${k / 100}: ${ztable(k / 100)} (paper ${want})`);
    }
    expect(bad).toEqual([]);
  });
  it('reads backwards as common.z_from_table (closest entry; on a tie the smaller z)', () => {
    expect([0.1, 0.9, 0.25, 0.5596, 0.4503, 0.05, 0.95, 0.975].map(z_from_table)).toEqual([-1.28, 1.28, -0.67, 0.15, -0.12, -1.65, 1.64, 1.96]);
  });
  it('rounds as Python does (exact value, ties to even)', () => {
    expect([round_py(0.125, 2), round_py(0.375, 2), round_py(2.675, 2), round_py(-1.4871, 2), round_py(1.005, 2), round_py(-0.001, 2)]).toEqual([0.12, 0.38, 2.67, -1.49, 1, 0]);
  });
});

describe('the lesson\'s numbers', () => {
  const M = { mu: 409000, sd: 19500 };
  it('(i) P(X < 380,000) = P(Z < -1.49) = 0.0681', () => {
    const r = read_normal({ ...M, mode: 'left', a: 380000, b: 0, p: 0 });
    expect([r.z_lo, r.area]).toEqual([-1.49, 0.0681]);
  });
  it('(ii) P(370,000 < X < 450,000) = 0.9821 - 0.0228 = 0.9593, in either order', () => {
    for (const [a, b] of [[370000, 450000], [450000, 370000]]) {
      const r = read_normal({ ...M, mode: 'between', a, b, p: 0 });
      expect([r.z_lo, r.z_hi, r.t_lo, r.t_hi, r.area]).toEqual([-2, 2.1, 0.0228, 0.9821, 0.9593]);
    }
  });
  it('(iii) the lower and upper 10%: 384,040 and 433,960', () => {
    expect(read_normal({ ...M, mode: 'find', a: 0, b: 0, p: 0.1 }).hi).toBe(384040);
    expect(read_normal({ ...M, mode: 'find', a: 0, b: 0, p: 0.9 }).hi).toBe(433960);
  });
  it('(iv) P(385,000 < X < d) = 0.4503: 0.1093 + 0.4503 = 0.5596, z = 0.15, d = 411,925', () => {
    const r = read_normal({ ...M, mode: 'find', a: 0, b: 0, p: 0.4503, from: 385000 });
    expect([r.z_lo, r.t_lo, r.target, r.z_hi, Math.round(r.hi)]).toEqual([-1.23, 0.1093, 0.5596, 0.15, 411925]);
  });
  it('the tyre: P(X > 40,000) = 0.2420, the 10% guarantee 30,100', () => {
    expect(read_normal({ mu: 36500, sd: 5000, mode: 'right', a: 40000, b: 0, p: 0 }).area).toBe(0.242);
    expect(read_normal({ mu: 36500, sd: 5000, mode: 'find', a: 0, b: 0, p: 0.1 }).hi).toBe(30100);
  });
  it('financial managers: between $30 and $35 is 0.7193; z rounded first', () => {
    expect([z_of(30, 32.62, 2.32), z_of(35, 32.62, 2.32)]).toEqual([-1.13, 1.03]);
    expect(read_normal({ mu: 32.62, sd: 2.32, mode: 'between', a: 30, b: 35, p: 0 }).area).toBe(0.7193);
  });
  it('the hand moves in round steps that reach the paper\'s values', () => {
    expect([hand_step(19500), hand_step(5000), hand_step(2.32)]).toEqual([500, 100, 0.05]);
    expect([decimals_of(409000, 19500), decimals_of(32.62, 2.32)]).toEqual([0, 2]);
  });
});
