// Compact API reference of manim-web for prompting language models:
// every public class with its constructor parameters (and defaults), plus the
// methods of the core classes. Writes ../ai/src/api_digest.generated.ts.
//   node tools/gen_api_digest.mjs
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');
const program = ts.createProgram([path.join(src, 'index.ts')], { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler });
const checker = program.getTypeChecker();
const mod = checker.getSymbolAtLocation(program.getSourceFile(path.join(src, 'index.ts')));
const CORE_METHODS = new Set(['Mobject', 'VMobject', 'Scene', 'Axes', 'NumberPlane', 'NumberLine', 'ValueTracker', 'MathTex', 'Text', 'DecimalNumber', 'Line', 'Circle', 'Arrow', 'VGroup']);
const clip = (s, n = 60) => (s.length > n ? s.slice(0, n - 1) + '…' : s);

function pyargsCall(node) {
  let found = null;
  node.forEachChild(function walk(n) {
    if (found) return;
    if (ts.isCallExpression(n) && n.expression.getText() === 'pyargs' && n.arguments.length >= 2 && ts.isArrayLiteralExpression(n.arguments[1])) found = n;
    else n.forEachChild(walk);
  });
  return found;
}
function ctorSignature(decl) {
  const ctor = decl.members.find(ts.isConstructorDeclaration);
  if (!ctor || !ctor.body) return null;
  const call = pyargsCall(ctor.body);
  if (!call) return null;
  const names = call.arguments[1].elements.map((e) => e.getText().replace(/['"]/g, ''));
  const defaults = {};
  const d = call.arguments[2];
  if (d && ts.isObjectLiteralExpression(d)) for (const p of d.properties) if (ts.isPropertyAssignment(p)) defaults[p.name.getText()] = clip(p.initializer.getText().replace(/\s+/g, ' '), 28);
  const pos = names.map((n) => (n in defaults ? `${n}=${defaults[n]}` : n));
  const kwOnly = Object.keys(defaults).filter((k) => !names.includes(k)).map((k) => `${k}=${defaults[k]}`);
  return [...pos, ...(kwOnly.length ? ['{' + kwOnly.join(', ') + '}'] : [])].join(', ');
}
function methods(decl) {
  const out = [];
  for (const m of decl.members) {
    if (!(ts.isMethodDeclaration(m) || ts.isGetAccessorDeclaration(m)) || !m.name || !ts.isIdentifier(m.name)) continue;
    const name = m.name.text;
    if (name.startsWith('_') || ts.getCombinedModifierFlags(m) & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected)) continue;
    if (ts.isGetAccessorDeclaration(m)) out.push(name);
    else out.push(`${name}(${m.parameters.map((p) => p.dotDotDotToken ? '...' : p.name.getText() + (p.initializer ? '=' + clip(p.initializer.getText(), 16) : '')).join(', ')})`);
  }
  return out;
}
const lines = [];
const functions = [], constants = [];
for (let e of checker.getExportsOfModule(mod)) {
  const name = e.getName();
  if (e.flags & ts.SymbolFlags.Alias) e = checker.getAliasedSymbol(e);
  let decl = e.valueDeclaration ?? e.declarations?.[0];
  if (!decl) continue;
  // `export const Circle = callable(_m.Circle)` -> the class itself
  if (ts.isVariableDeclaration(decl) && decl.initializer && ts.isCallExpression(decl.initializer) && decl.initializer.expression.getText() === 'callable') {
    let s = checker.getSymbolAtLocation(decl.initializer.arguments[0]);
    if (s && s.flags & ts.SymbolFlags.Alias) s = checker.getAliasedSymbol(s);
    const d = s?.valueDeclaration ?? s?.declarations?.[0];
    if (d) decl = d;
  }
  const file = path.relative(src, decl.getSourceFile().fileName);
  if (file.startsWith('utils/color/palettes') || file.startsWith('ext/py')) continue;
  if (ts.isClassDeclaration(decl)) {
    const sig = ctorSignature(decl);
    const base = decl.heritageClauses?.[0]?.types[0]?.expression.getText();
    lines.push(`${name}(${sig ?? ''})${base ? ' : ' + base : ''}`);
    if (CORE_METHODS.has(name)) lines.push('  ' + methods(decl).join('; '));
  } else if (ts.isFunctionDeclaration(decl) || (ts.isVariableDeclaration(decl) && decl.initializer && (ts.isArrowFunction(decl.initializer) || ts.isFunctionExpression(decl.initializer)))) {
    functions.push(name);
  } else if (ts.isVariableDeclaration(decl) && /^[A-Z][A-Z0-9_]*$/.test(name)) constants.push(name);
}
const digest = `# manim-web API (same names and semantics as Manim Community 0.21)
## Classes: Name(positional params, {keyword-only params}) : base
${lines.join('\n')}
## Functions
${functions.join(', ')}
## Constants
${constants.join(', ')}
`;
fs.writeFileSync(path.join(root, '../ai/src/api_digest.generated.ts'), `// GENERATED by manim-web/tools/gen_api_digest.mjs - do not edit.\nexport const API_DIGEST = ${JSON.stringify(digest)};\n`);
console.log(`api digest: ${lines.length} lines, ${digest.length} chars`);
