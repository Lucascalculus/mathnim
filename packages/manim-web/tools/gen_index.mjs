// Generates src/index.ts: re-exports every public module; classes are wrapped
// with callable() so they can be called without `new`, like Python.
//   node tools/gen_index.mjs
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');
const SKIP = new Set(['index.ts', 'utils/callable.ts', 'utils/registry.ts', 'utils/kwcall.ts']);
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d).sort()) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.endsWith('.test.ts')) {
      const rel = path.relative(src, p);
      if (!SKIP.has(rel) && !rel.startsWith('ext/py/')) files.push(rel);
    }
  }
})(src);

const program = ts.createProgram(files.map((f) => path.join(src, f)), { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, strict: true });
const checker = program.getTypeChecker();

const KW_NAMES = new Set(['kw', 'kwargs', 'o', 'opts', 'options', 'config']);
/** [names, kwIndex] for a parameter list, or null when it takes ...rest or destructures. */
function signature(params) {
  if (!params.length) return null;
  const names = [];
  let kwIndex = -1;
  for (const [i, p] of params.entries()) {
    if (p.dotDotDotToken) return i > 0 && i === params.length - 1 ? [names, i, 1] : null;
    if (!ts.isIdentifier(p.name)) return null;
    const name = p.name.text;
    if (name === 'this') return null;
    names.push(name);
    const t = p.type ? p.type.getText() : '';
    if (KW_NAMES.has(name) || /Kwargs|Record<|^\{/.test(t)) kwIndex = i;
  }
  return [names, kwIndex];
}
function classSignatures(decl) {
  const methods = {}, statics = {};
  for (const m of decl.members) {
    if (!ts.isMethodDeclaration(m) || !m.name || !ts.isIdentifier(m.name) || !m.body) continue;
    const mods = ts.getCombinedModifierFlags(m);
    if (mods & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected)) continue;
    const sig = signature(m.parameters);
    if (!sig) continue;
    (mods & ts.ModifierFlags.Static ? statics : methods)[m.name.text] = sig;
  }
  return [methods, statics];
}
function functionSignature(decl) {
  if (ts.isFunctionDeclaration(decl)) return signature(decl.parameters);
  if (ts.isVariableDeclaration(decl) && decl.initializer && (ts.isArrowFunction(decl.initializer) || ts.isFunctionExpression(decl.initializer))) return signature(decl.initializer.parameters);
  return null;
}
const seen = new Map();
const installs = [];
const ctorSigs = new Map();
const out = ['// GENERATED by tools/gen_index.mjs — do not edit by hand.', "import { callable } from './utils/callable';", "import { install_kwargs, kwfn } from './utils/kwcall';", "export { kwfn, install_kwargs } from './utils/kwcall';", "export { callable, add_construct_hook, type Callable } from './utils/callable';", "export { registry } from './utils/registry';"];
const body = [];
let n = 0;
for (const rel of files) {
  const sf = program.getSourceFile(path.join(src, rel));
  const sym = checker.getSymbolAtLocation(sf);
  if (!sym) continue;
  const spec = './' + rel.replace(/\.ts$/, '');
  const alias = '_m' + n++;
  const plain = [], types = [], classes = [], funcs = [];
  for (let e of checker.getExportsOfModule(sym)) {
    const name = e.getName();
    if (name === 'default') continue;
    let t = e;
    if (t.flags & ts.SymbolFlags.Alias) t = checker.getAliasedSymbol(t);
    const decl = t.declarations?.[0];
    const origin = decl ? path.relative(src, decl.getSourceFile().fileName) : rel;
    if (seen.has(name)) {
      if (seen.get(name) !== origin) console.warn(`duplicate export ${name}: ${seen.get(name)} vs ${origin} (keeping first)`);
      continue;
    }
    seen.set(name, origin);
    const isValue = !!(t.flags & ts.SymbolFlags.Value);
    const isClass = !!(t.flags & ts.SymbolFlags.Class) && decl && ts.isClassDeclaration(decl) && !(ts.getCombinedModifierFlags(decl) & ts.ModifierFlags.Abstract);
    if (isClass) {
      classes.push(name);
      const ctor = decl.members.find((m) => ts.isConstructorDeclaration(m));
      const csig = ctor ? signature(ctor.parameters) : null;
      // only fixed leading parameters need remapping (pure ...args constructors use pyargs)
      if (csig && csig[0].length) ctorSigs.set(`${alias}.${name}`, csig);
      const [methods, statics] = classSignatures(decl);
      if (Object.keys(methods).length || Object.keys(statics).length) installs.push([alias, name, methods, statics]);
    } else if (isValue && decl && origin === rel && functionSignature(decl)) funcs.push([name, functionSignature(decl)]);
    else if (isValue) plain.push(name);
    else types.push(name);
    if (!isClass && !isValue) continue;
    // abstract classes still get kwargs support
    if (!isClass && decl && ts.isClassDeclaration(decl)) {
      const [methods, statics] = classSignatures(decl);
      if (Object.keys(methods).length || Object.keys(statics).length) installs.push([alias, name, methods, statics]);
    }
  }
  if (!plain.length && !types.length && !classes.length && !funcs.length) continue;
  body.push(`// ${rel}`);
  if (plain.length || types.length) body.push(`export { ${[...plain, ...types.map((t) => `type ${t}`)].join(', ')} } from '${spec}';`);
  if (classes.length || funcs.length || installs.some((x) => x[0] === alias)) body.push(`import * as ${alias} from '${spec}';`);
  for (const c of classes) {
    const sig = ctorSigs.get(`${alias}.${c}`);
    body.push(`export const ${c} = callable(${alias}.${c}${sig ? ', ' + JSON.stringify(sig) : ''});`, `export type ${c} = ${alias}.${c};`);
  }
  for (const [f, sig] of funcs) body.push(`export const ${f} = kwfn(${alias}.${f}, ${JSON.stringify(sig)});`);
}
body.push('', '// keyword arguments for methods with fixed parameters (see utils/kwcall.ts)');
for (const [alias, name, methods, statics] of installs) body.push(`install_kwargs(${alias}.${name}, ${JSON.stringify(methods)}${Object.keys(statics).length ? ', ' + JSON.stringify(statics) : ''});`);
fs.writeFileSync(path.join(src, 'index.ts'), [...out, '', ...body, ''].join('\n'));
console.log(`index.ts: ${seen.size} names from ${files.length} modules`);
