import fs from 'node:fs';

const manifest = (file) => {
  const src = fs.readFileSync(file, 'utf8');
  const start = src.indexOf('= {', src.indexOf('export const MANIFEST')) + 2;
  const end = src.indexOf('\n};', start) + 2;
  return JSON.parse(src.slice(start, end));
};
