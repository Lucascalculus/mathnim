"""Shared helpers for the offline data of the fine-tuning course (parts B and C).

Everything here runs on a Mac without CUDA (CPU). Models are ungated Qwen2.5
checkpoints from the Hugging Face Hub, cached in ./.cache/hf next to this file.
Outputs are TypeScript data modules for @mathnim/visuals (the visuals package
does not import JSON), written with a fixed number of significant digits so
re-running gives the same files.

Run every script with the venv's python and -I, from any directory:
    apps/mathnim/tools/ft-data/.venv/bin/python -I apps/mathnim/tools/ft-data/<script>.py
"""
from __future__ import annotations

import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]  # repo root (apps/mathnim/tools/ft-data -> repo)
CACHE = HERE / ".cache" / "hf"
VIS_B = ROOT / "packages" / "visuals" / "src" / "ft" / "b"
VIS_C = ROOT / "packages" / "visuals" / "src" / "ft" / "c"

BASE = "Qwen/Qwen2.5-0.5B"
INSTRUCT = "Qwen/Qwen2.5-0.5B-Instruct"
# Pin exact revisions after the first download (printed by fetch()) for full reproducibility.
REVISIONS: dict[str, str | None] = {BASE: None, INSTRUCT: None}


def fetch(repo: str) -> Path:
    """Download (or reuse) a model snapshot; returns its local folder."""
    from huggingface_hub import snapshot_download

    os.environ.setdefault("HF_HUB_DISABLE_TELEMETRY", "1")
    path = snapshot_download(repo, revision=REVISIONS.get(repo), cache_dir=str(CACHE),
                             allow_patterns=["*.json", "*.safetensors", "*.txt", "merges.txt", "vocab.json"])
    print(f"{repo}: {path}")
    return Path(path)


def sig(x: float, digits: int = 4) -> float:
    """Round to `digits` significant digits (stable text output)."""
    if x == 0 or x != x:
        return 0.0
    return float(f"{x:.{digits}g}")


def ts_module(path: Path, header: str, exports: dict[str, object], types: str = "") -> None:
    """Write a TypeScript module with `export const NAME = <json>;` lines."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"// {line}" if line else "//" for line in header.strip().splitlines()]
    lines.append("// GENERATED by apps/mathnim/tools/ft-data - do not edit by hand.")
    lines.append("/* eslint-disable */")
    if types:
        lines.append(types.strip())
    for name, value in exports.items():
        text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        annot = f": {name}_T" if f"type {name}_T" in types else ""
        lines.append(f"export const {name}{annot} = {text};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path} ({path.stat().st_size // 1024} KB)")
